"""Write the batch-of-2026-10-27 sections into results/2026-10-27-followups.md, and print a summary.

    uv run python scripts/batch_writeup.py

Reads results/tables (run scripts/export_results.py first; scripts/check_batch.sh does both)
and outputs/orchestrator. Tables only, no interpretation. The sections live between two marker
lines and are rewritten in place on every run, so running it again never duplicates anything;
a config with no runs yet is listed as pending. Calls nothing.
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
WRITEUP = ROOT / "results" / "2026-10-27-followups.md"
ORCHESTRATOR = ROOT / "outputs" / "orchestrator"
START = "<!-- batch-2026-10-27: generated by scripts/batch_writeup.py, do not edit by hand -->"
END = "<!-- end batch-2026-10-27 -->"

CONFIGS = {
    "bundle_dialogue": "Escalation, solicited and fabricated assurances, Sam's double-check, "
    "a role that reserves the check, and claim/policy order. Length 5.",
    "bundle_team": "Bystanders, votes, group and forwarded claims, peers' earlier sends, "
    "chain of custody, and three- and four-hop relays. Length 5.",
    "bundle_protocol": "JSON task envelopes, provenance tags, and a request to paste the "
    "document's content. Length 5.",
    "lp_bundle": "Specificity and speaker label of the assurance, sampled half. Length 5.",
    "assurance_back_5": "Arm B's pair at length 50, arm F's assurance at backwards index 5.",
    "assurance_back_20": "Arm B's pair at length 50, arm F's assurance at backwards index 20.",
    "assurance_back_50": "Arm B's pair at length 50, arm F's assurance at backwards index 50.",
}
OUTCOMES = [
    "checked_then_declined",
    "checked_then_acted",
    "acted_without_check",
    "check_after_action",
    "no_check_no_action",
]
FLAGS = ["asked_for_verification", "reply_claims_check", "document_text_in_reply"]


def short(scenario: str) -> str:
    s = scenario.removeprefix("sharing_incontext_")
    for v in ("risky_", "benign_"):
        s = s.removeprefix(v)
    return s


def twin(scenario: str) -> str:
    return "risky" if "_risky" in scenario else "benign"


def rates(experiment: str) -> list[dict[str, str]]:
    path = TABLES / f"{experiment}.rates.csv"
    return list(csv.DictReader(path.open())) if path.exists() else []


def outcome_counts() -> dict[tuple, dict[str, int]]:
    out: dict[tuple, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    path = TABLES / "outcomes.csv"
    if not path.exists():
        return out
    for r in csv.DictReader(path.open()):
        key = (r["experiment"], r["model"], r["scenario"], r["pattern"], r["length"])
        out[key][r["outcome"]] += int(r["n"])
        out[key]["n"] += int(r["n"])
        for flag in FLAGS:
            out[key][flag] += int(r.get(f"n_{flag}") or 0)
    return out


def cell(r: dict[str, str]) -> str:
    return (
        f"{float(r['check_rate']):.2f} [{float(r['ci_low']):.2f}, {float(r['ci_high']):.2f}], "
        f"{r['unsafe']} unsafe"
    )


def section(experiment: str, counts: dict[tuple, dict[str, int]]) -> list[str]:
    rows = rates(experiment)
    lines = [f"## {experiment}.yaml", "", CONFIGS[experiment], ""]
    if not rows:
        return [*lines, "No runs yet.", ""]
    models = sorted({r["model"] for r in rows})
    lines += [
        f"Table: `tables/{experiment}.rates.csv`. Job ids: `README.md`.",
        "",
        "### Check rates, 95% Wilson intervals, unsafe sends",
        "",
        "| cell | twin | " + " | ".join(models) + " |",
        "|" + "---|" * (2 + len(models)),
    ]
    idx = {(r["model"], r["scenario"]): r for r in rows}
    scenarios = sorted({r["scenario"] for r in rows}, key=lambda s: (twin(s) != "risky", s))
    order = {s: i for i, s in enumerate(dict.fromkeys(short(s) for s in scenarios))}
    scenarios.sort(key=lambda s: (twin(s) != "risky", order[short(s)]))
    for s in scenarios:
        cells = [cell(idx[(m, s)]) if (m, s) in idx else "not run" for m in models]
        lines.append(f"| {short(s)} | {twin(s)} | " + " | ".join(cells) + " |")
    excluded = [r for r in rows if int(r["excluded"])]
    lines.append("")
    lines.append(
        "Excluded runs: "
        + "; ".join(
            f"{r['model']}, {short(r['scenario'])} {twin(r['scenario'])}: {r['excluded']}"
            for r in excluded
        )
        + "."
        if excluded
        else "No runs were excluded in any cell."
    )
    lines += [
        "",
        "### Outcomes and reply flags, risky cells",
        "",
        "| model | cell | " + " | ".join(OUTCOMES) + " | n | " + " | ".join(FLAGS) + " |",
        "|" + "---|" * (3 + len(OUTCOMES) + len(FLAGS)),
    ]
    for r in sorted(rows, key=lambda r: (r["model"], order[short(r["scenario"])])):
        if twin(r["scenario"]) != "risky":
            continue
        c = counts[(experiment, r["model"], r["scenario"], r["pattern"], r["length"])]
        lines.append(
            f"| {r['model']} | {short(r['scenario'])} | "
            + " | ".join(str(c.get(o, 0)) for o in OUTCOMES)
            + f" | {c.get('n', 0)} | "
            + " | ".join(str(c.get(f, 0)) for f in FLAGS)
            + " |"
        )
    return [*lines, ""]


def logprob_section() -> list[str]:
    path = TABLES / "lp_bundle.logprob.csv"
    lines = ["## lp_bundle.yaml, logprob half", ""]
    if not path.exists():
        return [*lines, "No logprob records yet.", ""]
    lines += [
        "Next-call probabilities at the `start` and `after_check` probes. Table: "
        "`tables/lp_bundle.logprob.csv`.",
        "",
        "| model | cell | twin | probe | p(call first) | p(check given call) | "
        "p(send given call) | n requests |",
        "|---|---|---|---|---|---|---|---|",
    ]
    rows = list(csv.DictReader(path.open()))
    rows.sort(key=lambda r: (r["model"], twin(r["scenario"]) != "risky", r["probe"], r["scenario"]))
    for r in rows:
        lines.append(
            f"| {r['model']} | {short(r['scenario'])} | {twin(r['scenario'])} | {r['probe']} | "
            f"{float(r['p_call_first']):.3f} | {float(r['p_check_given_call']):.3f} | "
            f"{float(r['p_send_given_call']):.3f} | {r['n_requests']} |"
        )
    return [*lines, ""]


def orchestrator_section() -> list[str]:
    lines = ["## Real orchestrator messages (orchestrate.yaml)", ""]
    files = sorted(ORCHESTRATOR.glob("*.jsonl")) if ORCHESTRATOR.exists() else []
    if not files:
        return [*lines, "No messages yet.", ""]
    lines += [
        "Saved in `outputs/orchestrator/<model>.jsonl`; classes by string rules (SPEC.md 3.2). A "
        "message can be both names_tool and asserts_done.",
        "",
        "| model | n | names_tool | mentions_access_list | asserts_done | none | errors |",
        "|---|---|---|---|---|---|---|",
    ]
    for f in files:
        n = errors = 0
        c: dict[str, int] = defaultdict(int)
        for line in f.read_text().splitlines():
            r = json.loads(line)
            if r.get("error") is not None:
                errors += 1
                continue
            n += 1
            for k, v in r["classes"].items():
                c[k] += bool(v)

        def share(k: str, c: dict[str, int] = c, n: int = n) -> str:
            return f"{c[k] / n:.2f} ({c[k]})" if n else "-"

        lines.append(
            f"| {f.stem} | {n} | {share('names_tool')} | {share('mentions_access_list')} | "
            f"{share('asserts_done')} | {share('none')} | {errors} |"
        )
    return [*lines, ""]


def summary() -> str:
    """One screen: risky-cell check rate per new arm and model."""
    by_arm: dict[str, dict[str, str]] = defaultdict(dict)
    models: set[str] = set()
    for experiment in CONFIGS:
        for r in rates(experiment):
            if twin(r["scenario"]) != "risky":
                continue
            arm = short(r["scenario"])
            if experiment.startswith("assurance_back"):
                arm = experiment
            elif experiment == "lp_bundle":
                arm = f"lp:{arm}"
            by_arm[arm][r["model"]] = f"{float(r['check_rate']):.2f}"
            models.add(r["model"])
    if not by_arm:
        return "No runs of the batch yet."
    ms = sorted(models)
    width = max(len(a) for a in by_arm) + 2
    head = "arm".ljust(width) + "".join(m.rjust(max(len(m), 6) + 2) for m in ms)
    lines = ["risky-cell check rate", head, "-" * len(head)]
    for arm, cells in by_arm.items():
        lines.append(
            arm.ljust(width) + "".join(cells.get(m, "-").rjust(max(len(m), 6) + 2) for m in ms)
        )
    return "\n".join(lines)


def main() -> int:
    counts = outcome_counts()
    block = [START, "", "# Batch of 2026-10-27 (PREREG.md), tables only", ""]
    for experiment in CONFIGS:
        block += section(experiment, counts)
    block += logprob_section() + orchestrator_section() + [END]
    text = WRITEUP.read_text()
    if START in text:
        head, _, rest = text.partition(START)
        _, _, tail = rest.partition(END)
        text = head + "\n".join(block) + tail
    else:
        text = text.rstrip("\n") + "\n\n" + "\n".join(block) + "\n"
    WRITEUP.write_text(text)
    print(f"updated {WRITEUP.name}")
    print(summary())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
